public class GenTables {
  public static void main(String[] a) {
    StringBuilder sb = new StringBuilder();
    sb.append("//! Unicode tables extracted from the reference JDK (").append(System.getProperty("java.runtime.version")).append("")
      .append("").append(").\n");
    sb.append("//! GENERATED by tools/GenTables.java - do not edit by hand.\n\n");
    // Digit runs: Character.digit(c, 10) for BMP chars.
    sb.append("/// Start code units of each run of 10 consecutive decimal digits (`Character.digit(c, 10)`), BMP only.\n");
    sb.append("pub const DIGIT_ZEROS: &[u16] = &[");
    int runs = 0;
    for (int c = 0; c <= 0xFFFF; c++) {
      if (Character.digit((char) c, 10) == 0) {
        for (int k = 0; k < 10; k++) if (Character.digit((char) (c + k), 10) != k) throw new RuntimeException("non-contiguous run at " + c);
        sb.append(runs++ % 8 == 0 ? "\n    " : " ").append(String.format("0x%04X,", c));
      }
    }
    // sanity: no digit outside the runs
    sb.append("\n];\n\n");
    for (int c = 0; c <= 0xFFFF; c++) {
      int d = Character.digit((char) c, 10);
      if (d > 0 && Character.digit((char) (c - d), 10) != 0) throw new RuntimeException("stray digit " + c);
    }
    // isSpaceChar ranges for c > 128
    sb.append("/// Inclusive ranges of `Character.isSpaceChar(c)` for code units above 0x80.\n");
    sb.append("pub const SPACE_CHAR_RANGES: &[(u16, u16)] = &[");
    int start = -1;
    for (int c = 0x81; c <= 0x10000; c++) {
      boolean sp = c <= 0xFFFF && Character.isSpaceChar((char) c);
      if (sp && start < 0) start = c;
      if (!sp && start >= 0) { sb.append("\n    ").append(String.format("(0x%04X, 0x%04X),", start, c - 1)); start = -1; }
    }
    sb.append("\n];\n\n");
    // isISOControl above 0x80
    int lo = -1, hi = -1;
    for (int c = 0x81; c <= 0xFFFF; c++) if (Character.isISOControl((char) c)) { if (lo < 0) lo = c; hi = c; }
    sb.append("/// `Character.isISOControl(c)` above 0x80 is exactly this inclusive range (checked at generation).\n");
    sb.append(String.format("pub const ISO_CONTROL_HIGH: (u16, u16) = (0x%04X, 0x%04X);\n", lo, hi));
    for (int c = 0x81; c <= 0xFFFF; c++) if (Character.isISOControl((char) c) != (c >= lo && c <= hi)) throw new RuntimeException("iso control not contiguous");
    System.out.print(sb);
  }
}
